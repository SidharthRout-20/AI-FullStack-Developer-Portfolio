def now_in_trip(trip: dict[str, Any], local: dt.datetime) -> dict[str, Any]:
    """Which trip day it is, the next stop and the time left today, from the traveller's local time."""
    today = local.date().isoformat()
    day = next((d for d in trip.get("days", []) if d.get("date") == today), None)
    minute = local.hour * 60 + local.minute
    out: dict[str, Any] = {"local_time": local.strftime("%Y-%m-%d %H:%M"), "day": None, "next": None, "current": None}
    if day is None:
        start, _ = trip_dates(trip)
        out["status"] = "before the trip" if start and local.date() < start else "not on a trip day"
        day = (trip.get("days") or [None])[0] if out["status"] == "before the trip" else None
        if day is None:
            return out
        minute = -1
    else:
        out["status"] = "on the trip"
    out["day"] = day["day"]
    for a in day.get("activities", []):
        start = travel.to_min(a.get("time", "09:00"))
        end = start + int(a.get("duration_min", 60))
        if start <= minute < end:
            out["current"] = a["id"]
        elif start > minute and out["next"] is None:
            out["next"] = a["id"]
    out["minutes_left_today"] = max(0, 22 * 60 - minute) if minute >= 0 else None
    return out


def compact_place(i: int, p: dict[str, Any]) -> dict[str, Any]:
    return {"ref": f"P{i}", "name": p["name"], "group": p["group"], "category": p.get("category"),
            "distance_m": p.get("distance_m"), "cuisine": p.get("cuisine"), "veg": p.get("veg") or None,
            "indoor": p.get("indoor") or None, "open_then": p.get("open"),
            "booking_link": any(link["kind"] in ("booking", "menu", "website") for link in p.get("links", []))}  # fmt: skip


ACTIONS = ("add_stop", "save_place", "move_earlier", "open_link")


def validate_suggestions(
    raw: list[dict[str, Any]],
    candidates: dict[str, dict[str, Any]],
    trip: dict[str, Any],
    anchor: dict[str, Any] | None,
) -> list[dict[str, Any]]:
    """Keep only actions on real things: places from the candidate list, activities and days that exist.
    Nothing is executed here; every action needs the traveller's confirmation in the UI."""
    acts = {a["id"]: (d["day"], a) for d in trip.get("days", []) for a in d.get("activities", [])}
    days = {d["day"] for d in trip.get("days", [])}
    out = []
    for s in raw[:6]:
        action = s.get("action")
        if action not in ACTIONS:
            continue
        item: dict[str, Any] = {"action": action, "why": str(s.get("why") or "")[:300], "confirm": True}
        if action in ("add_stop", "save_place", "open_link"):
            place = candidates.get(str(s.get("place_ref") or ""))
            if place is None:
                continue  # model referenced a place we never gave it: dropped, never shown
            item["place"] = place
            if action == "open_link":
                links = [lk for lk in place.get("links", []) if lk["kind"] in ("booking", "menu", "website")]
                if not links:
                    continue
                item["link"], item["external"] = links[0], True
            if anchor and anchor.get("lat") is not None:
                km = travel.km_between((anchor["lat"], anchor["lng"]), (place["lat"], place["lng"])) * 1.3
                item["route"] = {"from": anchor["name"], "km": round(km, 1), "walk_min": max(1, round(km / travel.WALK_KMH * 60)),
                                 "estimate": True}  # fmt: skip
        if action == "add_stop":
            day = s.get("day") if s.get("day") in days else (acts.get(anchor["id"], (None,))[0] if anchor else None)
            if day is None:
                continue
            item["day"] = day
            item["time"] = s["time"] if re.match(r"^([01]\d|2[0-3]):[0-5]\d$", str(s.get("time") or "")) else None
        if action == "move_earlier":
            ref = acts.get(str(s.get("activity_id") or ""))
            new_time = str(s.get("time") or "")
            if ref is None or not re.match(r"^([01]\d|2[0-3]):[0-5]\d$", new_time):
                continue
            if travel.to_min(new_time) >= travel.to_min(ref[1].get("time", "09:00")):
                continue
            item.update(day=ref[0], activity_id=ref[1]["id"], activity=ref[1]["name"], time=new_time,
                        from_time=ref[1].get("time"))  # fmt: skip
        out.append(item)
    return out


# ── post-trip ───────────────────────────────────────────────────────────────
def trip_summary(trip: dict[str, Any], expenses: list[dict[str, Any]], places: list[dict[str, Any]]) -> dict[str, Any]:
    days = trip.get("days", [])
    stops = [a for d in days for a in d.get("activities", []) if a.get("kind") != "transit"]
    km = sum(leg.get("km", 0) for d in days for leg in (d.get("route") or {}).get("legs", []))
    favourites = [a["name"] for a in stops
                  if a.get("pinned") or a.get("priority") == "must" or sum((a.get("votes") or {}).values()) > 0]  # fmt: skip
    money = budget_summary(trip.get("budget"), expenses)
    start, end = trip_dates(trip)
    kinds = defaultdict(int)
    for a in stops:
        kinds[a.get("kind", "outdoor")] += 1
    return {
        "title": trip.get("title"),
        "destinations": [d["name"] for d in trip.get("destinations") or []] or [trip.get("city", {}).get("name")],
        "dates": {"start": start.isoformat() if start else None, "end": end.isoformat() if end else None},
        "days": len(days),
        "stops": len(stops),
        "by_kind": dict(kinds),
        "distance_km": round(km, 1),
        "favourites": favourites[:12],
        "saved_places": [p["name"] for p in places][:20],
        "spend": {k: money[k] for k in ("currency", "budget_total", "actual_total", "estimated_total", "remaining")},
        "top_categories": sorted(
            ((c, v["actual"]) for c, v in money["by_category"].items() if v["actual"]), key=lambda x: -x[1]
        )[:3],  # fmt: skip
    }


def ceil5(m: float) -> int:
    return int(math.ceil(m / 5) * 5)


def destination_of(trip: dict[str, Any], day: dict[str, Any]) -> dict[str, Any]:
    """The destination a day takes place in (legacy single-city trips: the city)."""
    for dest in trip.get("destinations") or []:
        if dest["id"] == day.get("destination"):
            return dest
    return (trip.get("destinations") or [trip["city"]])[0]


def strip_refs(text: str, candidates: dict[str, dict[str, Any]]) -> str:
    """Remove the model-facing place refs from a reply: "Café X (P1)" → "Café X"; a bare "P1" → the place name."""
    for ref, place in candidates.items():
        text = re.sub(rf"\s*\(\s*{ref}\s*\)", "", text)
        text = re.sub(rf"\b{ref}\b", place["name"], text)
    return re.sub(r"[ \t]{2,}", " ", text).strip()
