def describe(tags: dict[str, str]) -> tuple[str, str]:
    """(natural group, human category) for an OpenStreetMap feature."""
    for key in _KEYS:
        value = tags.get(key)
        if not value:
            continue
        group = _TAG_GROUP.get(key, {}).get(value)
        if group is None:
            group = {"shop": "shopping", "craft": "shopping", "natural": "nature", "historic": "sights",
                     "railway": "transport", "public_transport": "transport", "aeroway": "airports"}.get(key, "sights")  # fmt: skip
        label = value.replace("_", " ") if value not in ("yes", "*") else key
        if key == "craft":
            label = f"artisan · {label}"
        return group, label
    return "sights", "place"


def _https(url: str | None) -> str | None:
    if not url:
        return None
    url = url.strip().split(";")[0].strip()
    if url.startswith("www."):
        url = "https://" + url
    p = urlparse(url)
    return url if p.scheme in ("http", "https") and p.netloc and " " not in url else None


def handoff_links(place: dict[str, Any]) -> list[dict[str, str]]:
    """External hand-offs that come from the provider data itself (never guessed URLs). TripWeaver doesn't place
    orders or bookings: these open the venue's own site, menu, booking page, phone or map."""
    links: list[dict[str, str]] = []
    for kind, key, label in (("booking", "reservation_url", "Book on the venue's site"),
                             ("menu", "menu", "Menu / order on the venue's site"),
                             ("website", "website", "Official website")):  # fmt: skip
        if url := _https(place.get(key)):
            if not any(link["url"] == url for link in links):
                links.append({"kind": kind, "label": label, "url": url, "source": "OpenStreetMap"})
    if place.get("phone"):
        tel = re.sub(r"[^\d+]", "", str(place["phone"]).split(";")[0])
        if len(tel) >= 6:
            links.append({"kind": "phone", "label": "Call", "url": f"tel:{tel}", "source": "OpenStreetMap"})
    if place.get("lat") is not None:
        lat, lng = place["lat"], place["lng"]
        links.append({"kind": "map", "label": "Open in OpenStreetMap", "source": "OpenStreetMap",
                      "url": f"https://www.openstreetmap.org/?mlat={lat}&mlon={lng}#map=18/{lat}/{lng}"})  # fmt: skip
    return links


def place_from(
    tags: dict[str, str], lat: float, lng: float, origin: tuple[float, float], osm_id: str | None
) -> dict[str, Any]:
    group, category = describe(tags)
    diet_v, diet_vg = tags.get("diet:vegetarian") or "", tags.get("diet:vegan") or ""
    p = {
        "name": tags["name"], "group": group, "category": category, "lat": lat, "lng": lng,
        "distance_m": round(travel.km_between(origin, (lat, lng)) * 1000),
        "cuisine": (tags.get("cuisine") or "").replace(";", ", ").replace("_", " ") or None,
        "veg": diet_v in ("yes", "only") or diet_vg in ("yes", "only"), "vegan": diet_vg in ("yes", "only"),
        "opening_hours": tags.get("opening_hours"), "website": _https(tags.get("website") or tags.get("contact:website")),
        "menu": _https(tags.get("website:menu") or tags.get("menu:url")),
        "reservation_url": _https(tags.get("reservation:website") or tags.get("booking")),
        "phone": tags.get("phone") or tags.get("contact:phone"), "reservation": tags.get("reservation"),
        "delivery": tags.get("delivery"), "takeaway": tags.get("takeaway"), "fee": tags.get("fee"),
        "wheelchair": tags.get("wheelchair"), "iata": tags.get("iata"), "osm_id": osm_id,
        "aerodrome_type": tags.get("aerodrome:type") or tags.get("aerodrome"),
        "military": bool(tags.get("military")) or tags.get("landuse") == "military" or "military" in (tags.get("aerodrome:type") or ""),
        "indoor": category in INDOOR_CATEGORIES, "source": "OpenStreetMap",
    }  # fmt: skip
    p["links"] = handoff_links(p)
    return p


def matches(p: dict[str, Any], group: str) -> bool:
    if group == p["group"]:
        return True
    cat = p.get("category") or ""
    return {
        "indoor": cat in INDOOR_CATEGORIES,
        "family": cat in {"zoo", "aquarium", "theme park", "playground", "water park", "planetarium", "park"},
        "nature": cat in {"park", "garden", "viewpoint", "nature reserve", "beach", "peak", "waterfall", "picnic site"},
        "experiences": cat in {"zoo", "aquarium", "theme park", "theatre", "cinema", "arts centre", "planetarium"},
        "sights": p["group"] == "sights",
    }.get(group, False)


def filter_discovery(
    places: list[dict[str, Any]],
    *,
    cuisine: str | None = None,
    veg: bool = False,
    vegan: bool = False,
    street_food: bool = False,
    free_only: bool = False,
    max_m: int | None = None,
    open_at: dt.datetime | None = None,
) -> list[dict[str, Any]]:
    out = []
    for p in places:
        if cuisine and cuisine.lower() not in (p.get("cuisine") or "").lower():
            continue
        if (veg and not p.get("veg")) or (vegan and not p.get("vegan")):
            continue
        if street_food and p.get("category") not in STREET_FOOD:
            continue
        if free_only and p.get("fee") != "no":
            continue
        if max_m is not None and p.get("distance_m", 0) > max_m:
            continue
        if open_at is not None:
            state = travel.is_open(p.get("opening_hours"), open_at)
            if state is False:
                continue
            p = {**p, "open": state}
        out.append(p)
    return out


def passenger_airports(places: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Airports travellers can fly into: military and private aerodromes (which may also carry IATA codes) are
    excluded; international/public ones first, then by distance."""
    usable = [
        p for p in places if not p.get("military") and (p.get("aerodrome_type") or "") not in ("private", "military")
    ]
    rank = {"international": 0, "public": 1, "regional": 2}
    return sorted(usable, key=lambda p: (rank.get(p.get("aerodrome_type") or "", 3), p.get("distance_m", 0)))


def match_specialities(items: list[dict[str, Any]], shops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Link AI-suggested local specialities to real nearby shops whose name or category mentions a search term."""
    out = []
    for it in items:
        terms = [t.lower() for t in it.get("search_terms", []) if len(t) >= 3]
        found = [s["name"] for s in shops if any(t in f"{s['name']} {s.get('category', '')}".lower() for t in terms)]
        out.append({**it, "shops": found[:5]})
    return out


# ── itinerary ───────────────────────────────────────────────────────────────
LABEL_TEXT = {
    "must_visit": "Must visit", "local_favourite": "Local favourite", "hidden_gem": "Hidden gem",
    "time_sensitive": "Time sensitive", "weather_dependent": "Weather dependent",
    "reservation_recommended": "Reservation recommended", "near_route": "Near your route",
    "traveller_favourite": "Traveller favourite",
}  # fmt: skip
USER_TAGS = ("local_favourite", "hidden_gem")  # only the traveller can apply these: no rating/popularity data exists


def _at(date: str | None, hhmm: str) -> dt.datetime | None:
    if not date:
        return None
    try:
        return dt.datetime.combine(dt.date.fromisoformat(date), dt.time(*divmod(travel.to_min(hhmm), 60)))
    except ValueError:
        return None


def stop_labels(a: dict[str, Any], day: dict[str, Any]) -> list[dict[str, str]]:
    """Evidence-backed labels. "Local favourite" and "Hidden gem" are never inferred (no free source has ratings or
    popularity); they appear only when the traveller tagged the stop, and say so."""
    out: list[dict[str, str]] = []

    def add(key: str, evidence: str, source: str) -> None:
        out.append({"id": key, "text": LABEL_TEXT[key], "evidence": evidence, "source": source})

    if a.get("priority") == "must":
        add("must_visit", "You marked this stop as a must.", "you")
    for tag in a.get("tags") or []:
        if tag in USER_TAGS:
            add(tag, "Your own tag.", "you")
    start = _at(day.get("date"), a.get("time", "09:00"))
    oh = a.get("opening_hours")
    if start and oh:
        end = start + dt.timedelta(minutes=int(a.get("duration_min", 60)))
        now_open, end_open, later = (
            travel.is_open(oh, start),
            travel.is_open(oh, end),
            travel.is_open(oh, end + dt.timedelta(minutes=60)),
        )
        if now_open and end_open is False:
            add("time_sensitive", f"Closes before your visit ends (opening hours: {oh}).", "OpenStreetMap")
        elif now_open and later is False:
            add("time_sensitive", f"Closes within an hour of your visit ending (opening hours: {oh}).", "OpenStreetMap")
    w = day.get("weather") or {}
    if a.get("kind") == "outdoor" and w:
        rain, feels = w.get("rain"), w.get("feels_max") if w.get("feels_max") is not None else w.get("tmax")
        if rain is not None and rain >= 40:
            add("weather_dependent", f"Outdoors, {rain}% chance of rain forecast that day.", "Open-Meteo forecast")
        elif feels is not None and feels >= 33:
            add("weather_dependent", f"Outdoors, feels like {round(feels)}°C that day.", "Open-Meteo forecast")
    if (a.get("reservation") or "").lower() in ("yes", "required", "recommended"):
        add("reservation_recommended", f"Venue data says reservation={a['reservation']}.", "OpenStreetMap")
    if (
        a.get("added") in ("nearby", "discovery", "companion")
        and a.get("distance_m") is not None
        and a["distance_m"] <= 600
    ):
        add("near_route", f"{a['distance_m']} m from {a.get('near') or 'a planned stop'}.", "distance")
    score = sum((a.get("votes") or {}).values())
    if score >= 2:
        add("traveller_favourite", f"+{score} from your group's votes.", "group votes")
    return out


def day_part(hhmm: str) -> str:
    m = travel.to_min(hhmm)
    return "morning" if m < 12 * 60 else "afternoon" if m < 17 * 60 else "evening"


def validate_day(day: dict[str, Any]) -> list[dict[str, str]]:
    """Deterministic schedule checks: overlaps (travel included), very late ends, closed-at-visit, unlocated stops."""
    issues: list[dict[str, str]] = []
    acts = day.get("activities", [])
    travel_min = {
        leg["to"]: leg.get("peak_minutes") or leg["minutes"] for leg in (day.get("route") or {}).get("legs", [])
    }
    for prev, cur in zip(acts, acts[1:], strict=False):
        free_at = (
            travel.to_min(prev.get("time", "09:00")) + int(prev.get("duration_min", 60)) + travel_min.get(cur["id"], 0)
        )
        if travel.to_min(cur.get("time", "09:00")) < free_at:
            issues.append({"type": "overlap", "activity_id": cur["id"],
                           "text": f"{cur['name']} starts before you can get there from {prev['name']} "
                                   f"(free at {travel.to_hhmm(free_at)}). Use Optimise route to re-time the day."})  # fmt: skip
    if acts:
        last = acts[-1]
        if travel.to_min(last.get("time", "09:00")) + int(last.get("duration_min", 60)) > 23 * 60 + 30:
            issues.append({"type": "late", "activity_id": last["id"], "text": f"{last['name']} ends after 23:30."})
    for a in acts:
        start = _at(day.get("date"), a.get("time", "09:00"))
        if start and travel.is_open(a.get("opening_hours"), start) is False:
            issues.append({"type": "closed", "activity_id": a["id"],
                           "text": f"{a['name']} looks closed at {a['time']} (opening hours: {a['opening_hours']})."})  # fmt: skip
        if a.get("lat") is None and a.get("kind") != "transit":
            issues.append({"type": "unlocated", "activity_id": a["id"], "text": f"{a['name']} isn't on the map yet."})
    return issues


def trip_dates(trip: dict[str, Any]) -> tuple[dt.date | None, dt.date | None]:
    dates = [dt.date.fromisoformat(d["date"]) for d in trip.get("days", []) if d.get("date")]
    return (min(dates), max(dates)) if dates else (None, None)


def phase(trip: dict[str, Any], today: dt.date) -> str:
    if trip.get("status") == "archived":
        return "archived"
    start, end = trip_dates(trip)
    if start is None or end is None:
        return "planning"
    return "upcoming" if today < start else "past" if today > end else "active"


# ── weather intelligence ───────────────────────────────────────────────────
def weather_alerts(day: dict[str, Any]) -> list[dict[str, str]]:
    """Derived from the stored forecast (not official warnings; Open-Meteo's free API doesn't provide those)."""
    w = day.get("weather") or {}
    out = []
    if (w.get("rain") or 0) >= 80:
        out.append({"type": "heavy_rain", "text": f"{w['rain']}% chance of rain"})
    feels = w.get("feels_max") if w.get("feels_max") is not None else w.get("tmax")
    if feels is not None and feels >= 35:
        out.append({"type": "heat", "text": f"Feels like {round(feels)}°C"})
    if w.get("tmin") is not None and w["tmin"] <= 0:
        out.append({"type": "frost", "text": f"Low of {round(w['tmin'])}°C"})
    if (w.get("wind_max") or 0) >= 50:
        out.append({"type": "wind", "text": f"Gusts up to {round(w['wind_max'])} km/h"})
    return out


def driest_window(
    hourly: list[list[float]], start_h: int = 8, end_h: int = 20, length: int = 3
) -> dict[str, Any] | None:
    """Lowest-rain `length`-hour window between start_h and end_h from hourly precipitation probability."""
    probs = {int(h): p for h, p in hourly if p is not None}
    best: tuple[float, int] | None = None
    for h in range(start_h, end_h - length + 1):
        window = [probs.get(x) for x in range(h, h + length)]
        if any(v is None for v in window):
            continue
        avg = sum(window) / length  # type: ignore[arg-type]
        if best is None or avg < best[0]:
            best = (avg, h)
    if best is None:
        return None
    return {"from": f"{best[1]:02d}:00", "to": f"{best[1] + length:02d}:00", "rain": round(best[0])}


def rain_spells(hourly: list[list[float]], threshold: int = 60) -> list[dict[str, Any]]:
    spells, cur = [], None
    for h, p in sorted((int(h), p) for h, p in hourly if p is not None):
        if p >= threshold:
            cur = cur or {"from": h, "to": h + 1, "max": p}
            cur["to"], cur["max"] = h + 1, max(cur["max"], p)
        elif cur:
            spells.append(cur)
            cur = None
    if cur:
        spells.append(cur)
    return [{"from": f"{s['from']:02d}:00", "to": f"{min(s['to'], 24):02d}:00", "max": round(s["max"])} for s in spells]


