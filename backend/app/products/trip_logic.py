def packing_list(trip: dict[str, Any]) -> list[dict[str, str]]:
    """A checklist from the trip's real conditions (forecast, length, party), not from a model."""
    days = trip.get("days", [])
    wx = [d.get("weather") or {} for d in days]
    n = max(1, len(days))
    party = (trip.get("party") or {}).get("type", "")
    travellers = f"{party} {(trip.get('request') or {}).get('travellers') or ''}".lower()
    items = [("ID / passport and visas", "always"), ("Phone charger and power adapter", "always"),
             ("Travel insurance details", "always"), ("Personal medication", "always"),
             (f"Clothes for {n} day{'s' if n > 1 else ''}", f"{n}-day trip")]  # fmt: skip
    if any((w.get("rain") or 0) >= 40 for w in wx):
        wet = sum(1 for w in wx if (w.get("rain") or 0) >= 40)
        items.append(("Umbrella or rain jacket", f"rain likely on {wet} day{'s' if wet > 1 else ''}"))
    if any((w.get("tmax") or 0) >= 28 for w in wx):
        items += [("Sunscreen and hat", "highs of 28°C or more"), ("Refillable water bottle", "hot days")]
    elif any((w.get("uv") or 0) >= 7 for w in wx):
        items.append(("Sunscreen", "UV index 7+"))
    if any(w.get("tmin") is not None and w["tmin"] <= 10 for w in wx):
        items.append(("Warm layer", "lows of 10°C or less"))
    if any((w.get("aqi") or 0) >= 100 for w in wx):
        items.append(("Face mask", "poor air quality forecast"))
    if any(a.get("kind") == "outdoor" for d in days for a in d.get("activities", [])):
        items.append(("Comfortable walking shoes", "outdoor stops planned"))
    if re.search(r"family|kid|child|toddler|baby", travellers):
        items += [("Snacks and entertainment for kids", "travelling with children"), ("Kids' medication", "children")]
    if len(trip.get("destinations") or []) > 1:
        items.append(("Onward tickets / transfer details", "multi-destination trip"))
    return [{"text": t, "why": why} for t, why in items]


# ── money ───────────────────────────────────────────────────────────────────
EXPENSE_CATEGORIES = ("lodging", "food", "transport", "activities", "shopping", "other")


def convert(amount: float, from_cur: str, to_cur: str, fx: dict[str, Any] | None) -> float | None:
    if from_cur.upper() == to_cur.upper():
        return round(amount, 2)
    if fx and fx.get("rate") and fx.get("to", to_cur).upper() == to_cur.upper():
        return round(amount * float(fx["rate"]), 2)
    return None


def budget_summary(budget: dict[str, Any] | None, expenses: list[dict[str, Any]]) -> dict[str, Any]:
    """Estimates and actual spend are always reported separately; unconverted foreign amounts are excluded from
    totals and listed, instead of being guessed."""
    budget = budget or {}
    cur = (budget.get("currency") or "EUR").upper()
    total = budget.get("total")
    cats: dict[str, dict[str, float]] = {c: {"budget": float((budget.get("categories") or {}).get(c) or 0), "actual": 0.0,
                                             "estimated": 0.0} for c in EXPENSE_CATEGORIES}  # fmt: skip
    by_day: dict[str, float] = defaultdict(float)
    unconverted: list[str] = []
    paid: dict[str, float] = defaultdict(float)
    owes: dict[str, float] = defaultdict(float)
    actual = estimated = 0.0
    for e in expenses:
        value = convert(float(e["amount"]), e.get("currency") or cur, cur, e.get("fx"))
        if value is None:
            unconverted.append(e["id"])
            continue
        cat = e.get("category") if e.get("category") in cats else "other"
        if e.get("kind") == "estimate":
            estimated += value
            cats[cat]["estimated"] += value
            continue
        actual += value
        cats[cat]["actual"] += value
        by_day[str(e.get("day") or e.get("date") or "unassigned")] += value
        payer = (e.get("paid_by") or "").strip()
        split = [s.strip() for s in (e.get("split_between") or []) if s.strip()] or ([payer] if payer else [])
        if payer and split:
            paid[payer] += value
            for person in split:
                owes[person] += value / len(split)
    people = sorted(set(paid) | set(owes))
    balances = {p: round(paid[p] - owes[p], 2) for p in people}
    r2 = lambda x: round(x, 2)  # noqa: E731
    return {
        "currency": cur,
        "budget_total": total,
        "actual_total": r2(actual),
        "estimated_total": r2(estimated),
        "remaining": r2(float(total) - actual) if total is not None else None,
        "remaining_after_estimates": r2(float(total) - actual - estimated) if total is not None else None,
        "over_budget": total is not None and actual > float(total),
        "by_category": {c: {k: r2(v) for k, v in vals.items()} for c, vals in cats.items()},
        "by_day": {k: r2(v) for k, v in sorted(by_day.items())},
        "unconverted": unconverted,
        "balances": balances,
        "settlements": settle_up(balances),
    }


def settle_up(balances: dict[str, float]) -> list[dict[str, Any]]:
    """Fewest simple transfers: largest debtor pays largest creditor."""
    debt = sorted(([p, -b] for p, b in balances.items() if b < -0.005), key=lambda x: -x[1])
    cred = sorted(([p, b] for p, b in balances.items() if b > 0.005), key=lambda x: -x[1])
    out, i, j = [], 0, 0
    while i < len(debt) and j < len(cred):
        amount = min(debt[i][1], cred[j][1])
        out.append({"from": debt[i][0], "to": cred[j][0], "amount": round(amount, 2)})
        debt[i][1] -= amount
        cred[j][1] -= amount
        if debt[i][1] <= 0.005:
            i += 1
        if cred[j][1] <= 0.005:
            j += 1
    return out


