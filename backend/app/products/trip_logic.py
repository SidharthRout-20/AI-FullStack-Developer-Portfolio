"""TripWeaver ecosystem logic: pure, deterministic functions (no I/O, no LLM), each unit-tested.

* discovery: OpenStreetMap selectors per category, feature → place mapping, provider hand-off links
* itinerary: evidence-backed stop labels, schedule validation, day parts, trip phase
* travel ops: packing checklist, weather alerts derived from the forecast, driest window
* money: budget summary (estimates kept apart from actual spend), currency conversion with dated rates, settle-up
* companion: context assembly and validation of model suggestions against real candidate places
* post-trip: summary

Rules shared by every function here: never invent ratings, popularity, prices, stock, opening hours or availability;
every label carries the evidence it rests on; anything a model produced is marked as AI-generated by the caller.
"""

